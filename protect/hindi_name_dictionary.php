if (!function_exists('formatHindiPartyName')) {
function formatHindiPartyName($name)
{
    $nameText = trim((string) $name);
    if ($nameText === '' || $nameText === '-') {
        return '-';
    }

    if (preg_match('/\p{Devanagari}/u', $nameText)) {
        return $nameText;
    }

    $fullNameDictionary = [
        'm j footware' => 'एम जे फुटवियर',
        'r yadav express' => 'आर यादव एक्सप्रेस',
        'sr enterprises' => 'एसआर एंटरप्राइजेज',
        'sk enterprises' => 'एसके एंटरप्राइजेज',
        'sk gupta' => 'एसके गुप्ता',
        'bk tyres' => 'बीके टायर्स',
        'gapl' => 'जीएपीएल',
        'mbhb' => 'एमबीएचबी',
        'sfc' => 'एसएफसी',
        'jtc' => 'जेटीसी',
        'dtdc' => 'डीटीडीसी',
        'ym' => 'वाईएम',
    ];

    $nameKey = strtolower($nameText);
    if (isset($fullNameDictionary[$nameKey])) {
        return $fullNameDictionary[$nameKey];
    }

    $parts = preg_split('/(\s+|[,&.()\/-]+)/', $nameText, -1, PREG_SPLIT_DELIM_CAPTURE | PREG_SPLIT_NO_EMPTY);
    if (!$parts) {
        return $nameText;
    }

    $output = '';
    foreach ($parts as $part) {
        if (preg_match('/^[a-zA-Z]+$/', $part)) {
            $output .= romanWordToHindi($part);
        } else {
            $output .= $part;
        }
    }

    return $output;
}
}

